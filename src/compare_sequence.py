#!/usr/bin/env python3
"""Compare best checkpoints without re-training or loading a backbone.

Examples:
  python src/compare_sequence.py --round resultados/sequencial/<queue> --wandb
  python src/compare_sequence.py --experiment <KAN experiment> --experiment <MLP experiment> --output <dir>
  python src/compare_sequence.py --experiment <dir> --output <dir> --allow-partial

Default: require every sequence to finish. Partial reports are explicitly labeled.
"""
import argparse
import json
from pathlib import Path

from utils.sequence_comparison import discover_experiments, generate_report, read_json, write_json


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--round", type=Path)
    source.add_argument("--experiment", action="append", type=Path)
    source.add_argument("--request", type=Path, help="Generated by train_sequence after the full grouped sequence")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--wandb", action="store_true")
    parser.add_argument("--entity", default="snaxofc10-utfpr-medianeira")
    parser.add_argument("--project", default="MOS-Prediction")
    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--allow-partial", action="store_true")
    args = parser.parse_args()
    options = {}
    tracking = {"enabled": args.wandb, "entity": args.entity, "project": args.project, "offline": args.offline}
    missing = []
    if args.request:
        request = read_json(args.request)
        experiments = request["experiments"]
        destination = Path(request["output"])
        options, tracking = request["options"], request["wandb"]
    elif args.round:
        experiments, missing = discover_experiments(args.round)
        destination = args.output or args.round / "comparison"
        manifest = read_json(args.round / "round.json")
        tracking["group"] = manifest.get("name")
    else:
        experiments = args.experiment
        if args.output is None:
            parser.error("--output is required with --experiment")
        destination = args.output
    try:
        if missing and not args.allow_partial:
            result = {"status": "waiting_for_complete_sequences", "missing": missing, "wandb_run_created": False}
            write_json(destination / "status.json", result)
        else:
            result = generate_report(experiments, destination, options, tracking, args.allow_partial)
        print(json.dumps(result, ensure_ascii=False, indent=2))
    finally:
        if args.request:
            (destination / ".scheduled.lock").unlink(missing_ok=True)


if __name__ == "__main__":
    main()
